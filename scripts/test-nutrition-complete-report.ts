import assert from "node:assert/strict";
import fs from "node:fs/promises";
import ExcelJS from "exceljs";
import { ALL_NUTRIENT_FIELDS, SOURCE_ONLY_NUTRIENT_FIELDS } from "../src/lib/nutrient-fields";
import { resolveMenu } from "../src/lib/nutrition-chat/core";
import { buildNutritionWorkbook, parseNutritionWorkbook } from "../src/lib/nutrition-chat/workbook";
import { workbookFixture } from "./test-nutrition-chat-workbook";
import { webNutritionReportInput } from "../src/app/tinh-khau-phan/nutrition-excel-download";

async function main() {
  const schema = (await fs.readFile("prisma/schema.prisma", "utf8")).split("model Food {")[1].split("model FoodPrice")[0];
  const fields = [...schema.matchAll(/^\s+(\w+)\s+Float\?/gm)].map(match => match[1]).filter(key => key !== "wastePercent");
  const covered = [...ALL_NUTRIENT_FIELDS, ...SOURCE_ONLY_NUTRIENT_FIELDS].map(field => field.key);
  assert.equal(new Set(covered).size, covered.length);
  assert.deepEqual(fields.filter(key => !covered.includes(key)), [], "every source nutrient has an explicit calculation or source-only mapping");
  assert.deepEqual(covered.filter(key => !fields.includes(key)), []);
  const fixture = workbookFixture();
  fixture.foods[0].nutrients.vitDMcg = 3;
  fixture.foods[0].nutrients.vitKMcg = 0;
  fixture.foods[0].nutrients.tocopherolBetaMg = 1.5;
  fixture.foods[0].sourceOnlyNutrients = { vitAMgVdd: 99, rniUnknownFattyAcidG: 8 };
  const menu = resolveMenu(fixture.menu.input, fixture.foods);
  const catalogue = [...Array.from({ length: 240 }, (_, i) => ({ ...fixture.foods[0], id: `padding-food-${i}` })), ...fixture.foods];
  const bytes = await buildNutritionWorkbook(menu, catalogue, { meta: { subjectName: "MẪU KIỂM THỬ", authorName: "Người lập mẫu", clinicalCourse: "Dữ liệu giả lập, không dùng đánh giá dinh dưỡng." } });
  await fs.mkdir("evidence/nutrition-chat", { recursive: true });
  await fs.writeFile("evidence/nutrition-chat/complete-report-test.xlsx", bytes);
  const wb = new ExcelJS.Workbook(); await wb.xlsx.load(Buffer.from(bytes) as unknown as ExcelJS.Buffer);
  assert.equal(wb.worksheets[0].name, "Bao cao");
  const report = wb.getWorksheet("Bao cao")!;
  const find = (label: string) => { let result = 0; report.eachRow((row, i) => { if (row.getCell(1).value === label) result = i; }); assert.ok(result, label); return result; };
  const cached = (row: number, col: number) => report.getCell(row, col).result;
  assert.equal(cached(find("Vitamin D"), 3), 6);
  assert.equal(cached(find("Vitamin K"), 3), 0);
  const detail = wb.getWorksheet("Thanh phan day du")!;
  let betaRow = 0; detail.eachRow((row, i) => { if (row.getCell(1).value === "Beta-tocopherol") betaRow = i; });
  assert.ok(betaRow); assert.equal(detail.getCell(betaRow, 3).result, 3);
  assert.equal(cached(find("Canxi"), 3), 20);
  assert.equal(cached(find("Canxi"), 7), 2);
  assert.match(String(cached(find("Canxi"), 8)), /Tổng một phần/);
  assert.equal(cached(find("Vitamin D"), 6), "—", "no invented target ratio");
  assert.equal(wb.getWorksheet("Thuc don")!.rowCount, 10, "only actual intake lines");
  const plan = wb.getWorksheet("Thuc don")!;
  assert.equal(plan.getCell("A6").value, "Ngày");
  assert.equal(plan.getCell("B6").value, "Bữa");
  assert.equal(plan.getCell("A7").result, "Ngày 1");
  assert.equal(plan.getCell("B7").result, "Trưa");
  assert.equal(plan.getCell("A8").result ?? "", "", "day label only at the start of its consecutive group");
  assert.equal(plan.getCell("C8").result ?? "", "", "same dish ingredients do not repeat the dish name");
  assert.equal(plan.getCell("A9").result ?? "", "", "a new meal does not repeat the day label");
  assert.equal(plan.getCell("C9").result, "Sữa", "a different dish starts a new label");
  assert.equal(plan.getCell("A10").result, "Ngày 2");
  assert.equal(plan.getCell("E7").result, 200);
  assert.equal(plan.getCell("F9").result, "ml");
  assert.equal(plan.getCell("G7").result, 260, "plan energy uses the resolved source amount");
  assert.equal(plan.getCell("H7").result, 5);
  assert.equal(plan.getCell("I7").result, 0.4);
  assert.equal(plan.getCell("J8").result, 0, "zero carbohydrate stays a real zero");
  assert.equal(plan.getCell("G9").result, 100, "portion source remains converted by the shared input calculation");
  assert.match(String(plan.getCell("G7").formula), /'Nhap khau phan'!/);
  assert.match(String(plan.getCell("A5").result), /VDD loại MA.*cả món.*không có danh sách nguyên liệu/);
  assert.equal(plan.views[0].showGridLines, true);
  assert.equal(plan.getCell("D7").font.size, 15);
  assert.notEqual(plan.getCell("G7").alignment.wrapText, true);
  assert.notEqual(plan.getCell("G7").alignment.shrinkToFit, true);
  assert.equal(wb.getWorksheet("Nhap khau phan")!.views[0].showGridLines, true);
  assert.equal(plan.getCell("K6").value, "Nguồn / ghi chú");
  assert.ok(!plan.getRow(6).values.toString().includes("Mục tiêu"));
  assert.ok(!plan.getRow(6).values.toString().includes("Đối chiếu"));
  assert.equal(wb.getWorksheet("Nhap khau phan")!.getRow(11).hidden, true);
  assert.equal(wb.getWorksheet("Phan tich")!.getRow(9).hidden, true);
  assert.equal(report.views[0].state, "normal");
  assert.equal(report.getCell("A1").font.name, "Times New Roman");
  assert.equal(report.pageSetup.paperSize, 9);
  const parsed = await parseNutritionWorkbook(bytes);
  assert.deepEqual(parsed.fields, menu.fields.map(field => field.key), "original conversation fields preserved when importing complete report");
  const custom = wb.getWorksheet("Tu nhap")!;
  const key = "tocopherolBetaMg";
  const customCol = [...Array.from({ length: custom.columnCount }, (_, i) => i + 1)].find(col => String(custom.getCell(6, col).value).startsWith("Beta-tocopherol"))!;
  assert.ok(customCol > 55, "new nutrient editable beyond old 40-column cap");
  custom.getCell(7, customCol).value = 4;
  const edited = await parseNutritionWorkbook(new Uint8Array(await wb.xlsx.writeBuffer()));
  assert.equal(edited.days[0].rows[2].customFood?.nutrients[key], 4);
  assert.equal(edited.days[0].rows[2].customFood?.source.confirmed, false);
  const typedFoods = structuredClone(fixture.foods);
  typedFoods[0].source.label = "VDD"; typedFoods[0].foodType = "MA";
  typedFoods[1].source.label = "RNI"; typedFoods[1].foodType = "MA";
  typedFoods[2].source.label = "RNI"; typedFoods[2].foodType = "TS";
  const typedInput = structuredClone(menu.input);
  typedInput.comparison = { mode: "none" };
  typedInput.days[0].rows[2].customFood!.source.label = "VDD";
  const noTarget = resolveMenu(typedInput, typedFoods);
  const kindBytes = await buildNutritionWorkbook(noTarget, typedFoods);
  await fs.writeFile("evidence/nutrition-chat/complete-report-kind-test.xlsx", kindBytes);
  const noTargetBook = new ExcelJS.Workbook(); await noTargetBook.xlsx.load(Buffer.from(kindBytes) as unknown as ExcelJS.Buffer);
  assert.match(String(noTargetBook.getWorksheet("Doi chieu")!.getCell("A7").value), /Chưa đặt mốc/);
  const typedPlan = noTargetBook.getWorksheet("Thuc don")!;
  assert.equal(typedPlan.getCell("D6").value, "Thực phẩm\nthành phần");
  assert.equal(typedPlan.getCell("C7").result, typedFoods[0].name, "VDD MA keeps its actual whole-dish name");
  assert.equal(typedPlan.getCell("D7").result, "Không có dữ liệu thành phần", "VDD MA does not pretend to have ingredients");
  assert.equal(typedPlan.getCell("C8").result, "Cơm với thịt", "RNI ingredient starts its own dish group after a whole dish");
  assert.equal(typedPlan.getCell("D8").result, typedFoods[2].name, "RNI ingredient retains its own row");
  assert.equal(typedPlan.getCell("D9").result, typedInput.days[0].rows[2].customFood!.name, "a custom source labelled VDD is not canonical VDD MA");
  assert.equal(typedPlan.getCell("D10").result, typedFoods[1].name, "RNI food type alone does not imply missing ingredients");
  const typedImported = await parseNutritionWorkbook(kindBytes);
  assert.deepEqual(typedImported.days.map(day => day.rows.length), [3, 1]);
  assert.equal(typedImported.days[0].rows[0].dish, "Cơm với thịt", "presentation does not replace the input dish alias");
  assert.equal(typedImported.days[0].rows[1].foodId, typedFoods[2].id);
  const changedInput = structuredClone(menu.input);
  changedInput.days.unshift({ id: "empty-day", label: "Ngày chưa nhập", date: "", rows: [] });
  changedInput.days[1].rows[0].servings = 2;
  changedInput.days[1].rows[1].quantity = null;
  changedInput.days[1].rows.push({ ...changedInput.days[1].rows[0], id: "return-to-dish" });
  changedInput.days[2].rows[0].dish = changedInput.days[1].rows[0].dish;
  changedInput.days[2].rows[0].meal = changedInput.days[1].rows[0].meal;
  const changedMenu = resolveMenu(changedInput, fixture.foods);
  const changedBook = new ExcelJS.Workbook(); await changedBook.xlsx.load(Buffer.from(await buildNutritionWorkbook(changedMenu, fixture.foods)) as unknown as ExcelJS.Buffer);
  const changedPlan = changedBook.getWorksheet("Thuc don")!;
  assert.equal(changedPlan.getCell("A7").result, "Ngày 1", "empty days do not create empty plan rows");
  assert.equal(changedPlan.getCell("E7").result, 400, "displayed quantity covers all servings");
  assert.equal(changedPlan.getCell("G7").result, 520, "displayed nutrition covers the same servings");
  assert.equal(changedPlan.getCell("E8").result, "—");
  assert.equal(changedPlan.getCell("G8").result, "—", "missing quantity is not zero nutrition");
  assert.equal(changedPlan.getCell("C10").result, "Cơm với thịt", "a nonconsecutive return to a dish repeats its label");
  assert.equal(changedPlan.getCell("A11").result, "Ngày 2");
  assert.equal(changedPlan.getCell("C11").result, "Cơm với thịt", "same dish in another day starts a new group");
  const regrouped = await parseNutritionWorkbook(new Uint8Array(await changedBook.xlsx.writeBuffer()));
  assert.deepEqual(regrouped.days.map(day => day.rows.length), [0, 4, 1], "presentation does not alter the input/import contract");
  assert.equal(regrouped.days[1].rows[1].dish, "Cơm với thịt", "input retains the repeated dish needed for calculations and import");
  const webRow = { uid: "a", meal: "Trưa", dish: "Cơm", foodId: "test-rice-a", foodName: "Cơm", grams: 200, inputGrams: 100, inputBasis: "edible" as const, conversionFactor: 2, wastePercent: 0, note: "", nutrients: {}, classify: { foodGroup: null, proteinOrigin: null, giLevel: null, purinLevel: null, cholesterolLevel: null } };
  const input = webNutritionReportInput([{ id: "day", label: "Ngày 1", date: "", rows: [webRow, { ...webRow, foodId: "" }] }], null);
  assert.equal(input.days[0].rows.length, 1, "empty web placeholders never masquerade as food lines");
  assert.equal(resolveMenu(input, fixture.foods).totals.energyKcal.value, 260, "web conversion agrees with conversation engine");
  const dense = Object.fromEntries(ALL_NUTRIENT_FIELDS.map(field => [field.key, field.key === "energyKcal" ? 130 : 1]));
  const oversizedCatalogue = [...fixture.foods, ...Array.from({ length: 5900 }, (_, i) => ({ ...fixture.foods[0], id: `dense-test-${i}`, nutrients: dense }))];
  await assert.rejects(buildNutritionWorkbook(menu, oversizedCatalogue), /an toàn/, "reject excessive allocation before constructing a full workbook");
  console.log(JSON.stringify({ sourceFields: fields.length, calculated: ALL_NUTRIENT_FIELDS.length, sourceOnly: SOURCE_ONLY_NUTRIENT_FIELDS.length, bytes: bytes.length, reportRows: report.rowCount, result: "complete report and import checks passed" }));
}
main().catch(error => { console.error(error); process.exitCode = 1; });
