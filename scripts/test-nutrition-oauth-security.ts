import assert from "node:assert/strict";
import {
  allowedNutritionRedirects, connectionCsrf, consentCsrf, DEFAULT_NUTRITION_SCOPES, getNutritionPublicUrl,
  getNutritionResourceUrl, hashNutritionToken, INTERACTION_SECONDS, NutritionSecurityError,
  oauthAuthorizationRedirect, oneParam, parseNutritionScopes, randomNutritionToken,
  readConsentInteraction, registrationInput, signConsentInteraction, validateConnectionCsrf, validateConsentCsrf,
  validateNutritionOrigin, validatePkceChallenge, validateRedirectUri, validateResource, verifyPkce, type ConsentInteraction,
} from "../src/lib/nutrition-chat/oauth-validation";
import { readNutritionForm, readNutritionJson, readNutritionText } from "../src/lib/nutrition-chat/http";

const saved = { ...process.env };
let checks = 0;
function expectError(fn: () => unknown, code: string) {
  assert.throws(fn, error => error instanceof NutritionSecurityError && error.code === code); checks++;
}
async function expectAsyncError(fn: () => Promise<unknown>, code: string) {
  await assert.rejects(fn, error => error instanceof NutritionSecurityError && error.code === code); checks++;
}
function bodyRequest(body: BodyInit, headers: Record<string, string>) {
  return new Request("https://dinhduong2598.food/test", { method: "POST", body, headers, duplex: "half" } as RequestInit & { duplex: "half" });
}

async function main() {
  try {
    delete process.env.NUTRITION_PUBLIC_URL;
    delete process.env.NUTRITION_OAUTH_REDIRECT_URIS;
    delete process.env.NUTRITION_ALLOWED_ORIGINS;
    process.env.APP_SECRET = "unit-test-placeholder-never-a-production-secret";
    assert.equal(getNutritionPublicUrl(), "https://dinhduong2598.food"); checks++;
    process.env.NUTRITION_PUBLIC_URL = "http://localhost:3018";
    assert.equal(getNutritionPublicUrl(), "http://localhost:3018"); checks++;
    process.env.NUTRITION_PUBLIC_URL = "https://user:pass@example.com";
    expectError(getNutritionPublicUrl, "server_error");
    process.env.NUTRITION_PUBLIC_URL = "http://example.com";
    expectError(getNutritionPublicUrl, "server_error");
    process.env.NUTRITION_PUBLIC_URL = "https://dinhduong2598.food/evil";
    expectError(getNutritionPublicUrl, "server_error");
    delete process.env.NUTRITION_PUBLIC_URL;

    const callback = allowedNutritionRedirects()[0];
    assert.equal(validateRedirectUri(callback, [callback]), callback); checks++;
    for (const uri of [`${callback}/`, `${callback}?next=evil`, "https://chatgpt.com.evil.test/connector_platform_oauth_redirect", "http://127.0.0.1/callback", "https://chatgpt.com@evil.test/callback", "javascript:alert(1)"]) {
      expectError(() => validateRedirectUri(uri), "invalid_redirect_uri");
    }
    expectError(() => validateRedirectUri(callback, ["https://claude.ai/api/mcp/auth_callback"]), "invalid_redirect_uri");
    process.env.NUTRITION_OAUTH_REDIRECT_URIS = JSON.stringify(["https://platform.openai.com/apps-manage/oauth"]);
    assert.equal(validateRedirectUri("https://platform.openai.com/apps-manage/oauth"), "https://platform.openai.com/apps-manage/oauth"); checks++;
    process.env.NUTRITION_OAUTH_REDIRECT_URIS = JSON.stringify(["https://evil.test/#fragment"]);
    expectError(allowedNutritionRedirects, "server_error");
    delete process.env.NUTRITION_OAUTH_REDIRECT_URIS;

    assert.deepEqual(parseNutritionScopes(undefined), DEFAULT_NUTRITION_SCOPES); checks++;
    assert.deepEqual(parseNutritionScopes(undefined, ["nutrition:read"]), ["nutrition:read"]); checks++;
    assert.deepEqual(parseNutritionScopes("nutrition:read nutrition:read"), ["nutrition:read"]); checks++;
    expectError(() => parseNutritionScopes("admin"), "invalid_scope");
    expectError(() => parseNutritionScopes("nutrition:write", ["nutrition:read"]), "invalid_scope");
    expectError(() => parseNutritionScopes("nutrition:read\nadmin"), "invalid_scope");
    expectError(() => parseNutritionScopes(""), "invalid_scope");
    assert.equal(validateResource(getNutritionResourceUrl()), getNutritionResourceUrl()); checks++;
    expectError(() => validateResource("https://dinhduong2598.food/api/nutrition/v1/mcp/"), "invalid_target");
    expectError(() => validateResource(undefined), "invalid_target");
    expectError(() => oneParam(new URLSearchParams("client_id=a&client_id=b"), "client_id"), "invalid_request");
    expectError(() => oneParam(new URLSearchParams("state=%00"), "state"), "invalid_request");
    expectError(() => oneParam(new URLSearchParams(), "state"), "invalid_request");

    // RFC7636 published PKCE vector, not a test generated by implementation.
    const verifier = "dBjftJeZ4CVP-mB92K27uhbUJU1p1r_wW1gFWFOEjXk";
    const challenge = "E9Melhoa2OwvFrEMTJguCHaoeK1t8URWbuGJSstw-cM";
    assert.equal(hashNutritionToken(verifier), challenge); checks++;
    assert.equal(verifyPkce(verifier, challenge), true); checks++;
    assert.equal(verifyPkce("wrong", challenge), false); checks++;
    assert.equal(verifyPkce(verifier, `${challenge.slice(0, -1)}X`), false); checks++;
    expectError(() => validatePkceChallenge(challenge, "plain"), "invalid_request");
    expectError(() => validatePkceChallenge("not-base64", "S256"), "invalid_request");

    const now = Date.now();
    const interaction: ConsentInteraction = {
      interactionId: randomNutritionToken(), clientId: `nc_${randomNutritionToken()}`, redirectUri: callback,
      codeChallenge: challenge, scopes: ["nutrition:read"], state: "client-state", issuer: getNutritionPublicUrl(),
      audience: getNutritionResourceUrl(), exp: now + INTERACTION_SECONDS * 1000,
    };
    const sealed = signConsentInteraction(interaction);
    assert.deepEqual(readConsentInteraction(sealed, now), interaction); checks++;
    expectError(() => readConsentInteraction(`${sealed.slice(0, -1)}X`, now), "invalid_request");
    expectError(() => readConsentInteraction(sealed, now + INTERACTION_SECONDS * 1000 + 1), "invalid_request");
    expectError(() => readConsentInteraction(signConsentInteraction({ ...interaction, issuer: "https://evil.test" }), now), "invalid_request");
    const csrf = consentCsrf(interaction, "user-a");
    validateConsentCsrf(interaction, "user-a", csrf); checks++;
    expectError(() => validateConsentCsrf(interaction, "user-b", csrf), "invalid_request");
    expectError(() => validateConsentCsrf({ ...interaction, interactionId: randomNutritionToken() }, "user-a", csrf), "invalid_request");
    validateConnectionCsrf("user-a", connectionCsrf("user-a")); checks++;
    expectError(() => validateConnectionCsrf("user-b", connectionCsrf("user-a")), "invalid_request");
    expectError(() => validateConnectionCsrf("user-a", connectionCsrf("user-a", Math.floor(Date.now() / 3_600_000) - 2)), "invalid_request");
    for (const params of [{ code: "opaque" }, { error: "access_denied" }] as Record<string, string>[]) {
      const redirect = new URL(oauthAuthorizationRedirect(interaction, params));
      assert.equal(redirect.searchParams.get("state"), interaction.state); checks++;
      assert.equal(redirect.searchParams.get("iss"), getNutritionPublicUrl()); checks++;
    }
    process.env.APP_SECRET = "short";
    expectError(() => signConsentInteraction(interaction), "server_error");
    process.env.APP_SECRET = "unit-test-placeholder-never-a-production-secret";

    const dcr = { client_name: "Claude", redirect_uris: ["https://claude.ai/api/mcp/auth_callback"], token_endpoint_auth_method: "none" };
    assert.equal(registrationInput(dcr).authMethod, "none"); checks++;
    assert.equal(registrationInput({ ...dcr, token_endpoint_auth_method: undefined }).authMethod, "client_secret_basic"); checks++;
    expectError(() => registrationInput({ ...dcr, redirect_uris: ["https://evil.test/callback"] }), "invalid_redirect_uri");
    expectError(() => registrationInput({ ...dcr, client_name: "\nSpoof" }), "invalid_client_metadata");
    expectError(() => registrationInput({ ...dcr, grant_types: ["client_credentials"] }), "invalid_client_metadata");
    expectError(() => registrationInput({ ...dcr, token_endpoint_auth_method: "private_key_jwt", jwks_uri: "http://169.254.169.254/latest/meta-data" }), "invalid_client_metadata");
    // Extension URL metadata is ignored and never fetched (no SSRF surface).
    assert.equal(registrationInput({ ...dcr, logo_uri: "http://169.254.169.254/", client_uri: "file:///etc/passwd" }).name, "Claude"); checks++;

    validateNutritionOrigin(new Request(getNutritionResourceUrl())); checks++;
    validateNutritionOrigin(new Request(getNutritionResourceUrl(), { headers: { Origin: getNutritionPublicUrl() } }), true); checks++;
    expectError(() => validateNutritionOrigin(new Request(getNutritionResourceUrl()), true), "invalid_request");
    expectError(() => validateNutritionOrigin(new Request(getNutritionResourceUrl(), { headers: { Origin: "null" } })), "invalid_request");
    expectError(() => validateNutritionOrigin(new Request(getNutritionResourceUrl(), { headers: { Origin: "https://evil.test" } })), "invalid_request");
    process.env.NUTRITION_ALLOWED_ORIGINS = "https://chatgpt.com";
    validateNutritionOrigin(new Request(getNutritionResourceUrl(), { headers: { Origin: "https://chatgpt.com" } })); checks++;
    expectError(() => validateNutritionOrigin(new Request(getNutritionResourceUrl(), { headers: { Origin: "https://chatgpt.com" } }), true), "invalid_request");

    assert.deepEqual(await readNutritionJson(bodyRequest('{"name":"Cơm"}', { "Content-Type": "application/json; charset=utf-8" })), { name: "Cơm" }); checks++;
    await expectAsyncError(() => readNutritionJson(bodyRequest("{}", { "Content-Type": "text/plain" })), "unsupported_media_type");
    await expectAsyncError(() => readNutritionJson(bodyRequest("{", { "Content-Type": "application/json" })), "invalid_request");
    await expectAsyncError(() => readNutritionText(bodyRequest("a", { "Content-Length": "100" }), 10), "request_too_large");
    await expectAsyncError(() => readNutritionText(bodyRequest("a", { "Content-Length": "-1" }), 10), "request_too_large");
    await expectAsyncError(() => readNutritionText(bodyRequest("01234567890", {}), 10), "request_too_large");
    await expectAsyncError(() => readNutritionText(bodyRequest(new Uint8Array([0xff]), {})), "invalid_request");
    const bytes = new TextEncoder().encode("Cơm");
    const chunks = new ReadableStream<Uint8Array>({ start(controller) { controller.enqueue(bytes.slice(0, 2)); controller.enqueue(bytes.slice(2)); controller.close(); } });
    assert.equal(await readNutritionText(bodyRequest(chunks, {})), "Cơm"); checks++;
    const stalled = new ReadableStream<Uint8Array>({ start() {} });
    await expectAsyncError(() => readNutritionText(bodyRequest(stalled, {}), 10, 30), "request_timeout");
    const form = await readNutritionForm(bodyRequest("client_id=first&client_id=second", { "Content-Type": "application/x-www-form-urlencoded" }));
    expectError(() => oneParam(form, "client_id"), "invalid_request");
    console.log(`Nutrition OAuth validation/security: ${checks} checks passed. Pure fixtures only; no DB writes.`);
  } finally {
    for (const key of Object.keys(process.env)) if (!(key in saved)) delete process.env[key];
    Object.assign(process.env, saved);
  }
}
main().catch(error => { console.error(error instanceof Error ? error.message : "Test failed"); process.exitCode = 1; });
